"""Generate the eICU-CRD DEMO extraction from the eICU extraction.

The demo (physionet-data.eicu_crd_demo, Open Data Commons ODbL v1.0) is run
through exactly the same SQL as the full eICU-CRD extraction. This script
copies sql/eicu/v2_0*.sql to sql/eicu_demo/<name>_demo.sql and changes only:

    physionet-data.eicu_crd.<t>    ->  physionet-data.eicu_crd_demo.<t>   (source)
    eicu-ext.eicu_ext_data.<t>     ->  eicu-ext.eicu_ext_data.<t>_demo    (target)

The target stays in the same dataset (a separate dataset was refused on
permissions), and every table the demo writes or reads there carries the
suffix `_demo`, so the full extraction's tables cannot be overwritten.

Three checks run on every file:
  1. every CREATE OR REPLACE TABLE writes to a `eicu-ext.eicu_ext_data.*_demo`
     table (no write can reach a main table);
  2. no reference to the full source or to an unsuffixed target remains;
  3. undoing the two mappings reproduces the source byte for byte.
Re-run whenever sql/eicu/ changes; never edit sql/eicu_demo/*.sql by hand.

    python sql/eicu_demo/make_demo_sql.py
"""
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.join(HERE, "..", "eicu")
SRC_OLD, SRC_NEW = "physionet-data.eicu_crd.", "physionet-data.eicu_crd_demo."
TGT = re.compile(r"eicu-ext\.eicu_ext_data\.(?!__TABLES__\b|INFORMATION_SCHEMA\b)([A-Za-z0-9_]+)")
# Quoted table names (only in commented-out audit queries) get the suffix too,
# so an uncommented audit reads the demo tables.
LIT = re.compile(r"'(v2_[a-z0-9_]*_eicu)'")
BANNER = ("-- GENERATED by sql/eicu_demo/make_demo_sql.py from sql/eicu/{name}.\n"
          "-- Identical to the source except that\n"
          "--   physionet-data.eicu_crd.<t>  -> physionet-data.eicu_crd_demo.<t>  (source, ODbL v1.0)\n"
          "--   eicu-ext.eicu_ext_data.<t>   -> eicu-ext.eicu_ext_data.<t>_demo   (target)\n"
          "-- Do not edit by hand.\n")

# DEMO TYPE ADAPTERS. The demo release stores a few columns with a different
# type from the full eICU-CRD. Each adapter below is written to give the same
# result under EITHER type, so it changes no logic; it is declared here, its
# match count is asserted, it is listed in the file's banner, and the round
# trip undoes it before the byte-for-byte comparison.
#   medication.drugordercancelled: STRING 'Yes'/'No' in the full release,
#   BOOL in the demo. CAST(... AS STRING) gives 'Yes'/'No' or 'true'/'false';
#   a cancelled order is excluded under both.
#   vitalperiodic.temperature: FLOAT64 in the full release, STRING in the
#   demo. SAFE_CAST is CAST on a FLOAT64 column; on a STRING column it maps a
#   non-numeric entry to NULL, and filtering on the cast value drops it, as a
#   NULL reading is dropped in the full release.
# Columns whose type differs but which the extraction does not read (cvp,
# etco2, volumeoffluid, prn, drugivadmixture, the vitalaperiodic haemodynamic
# columns, apacheapsvar.heartrate) need no adapter. respiratorycare differs
# only in the case of its column names, which BigQuery resolves regardless.
ADAPTERS = {
    "v2_03a_signals_hourly_raw_eicu.sql": [
        ("CAST(temperature AS FLOAT64), 'vitalperiodic'",
         "SAFE_CAST(temperature AS FLOAT64), 'vitalperiodic'", 1),
        ("FROM vp WHERE temperature IS NOT NULL",
         "FROM vp WHERE SAFE_CAST(temperature AS FLOAT64) IS NOT NULL", 1),
    ],
    "v2_02b_interventions_eicu.sql": [
        ("COALESCE(m.drugordercancelled, 'No') != 'Yes'",
         "COALESCE(CAST(m.drugordercancelled AS STRING), 'No') NOT IN ('Yes', 'true')", 2),
        ("COALESCE(drugordercancelled, 'No') != 'Yes'",
         "COALESCE(CAST(drugordercancelled AS STRING), 'No') NOT IN ('Yes', 'true')", 1),
    ],
}

n_files = n_creates = 0
for src in sorted(glob.glob(os.path.join(SRC_DIR, "v2_0*.sql"))):
    name = os.path.basename(src)
    raw = open(src, "rb").read()
    text = raw.decode("utf-8")
    assert "_demo" not in text, f"{name}: source already mentions _demo"

    out = text.replace(SRC_OLD, SRC_NEW)
    out = TGT.sub(lambda m: m.group(0) + "_demo", out)
    out = LIT.sub(lambda m: "'" + m.group(1) + "_demo'", out)
    adapters = ADAPTERS.get(name, [])
    for old, new, n in adapters:
        c = out.count(old)
        assert c == n, f"{name}: adapter expected {n} match(es), found {c}: {old}"
        out = out.replace(old, new)

    # 1. every write goes to a *_demo table in the target dataset
    creates = re.findall(r"CREATE\s+OR\s+REPLACE\s+TABLE\s+`?([^\s`(]+)`?", out, flags=re.I)
    for t in creates:
        assert t.startswith("eicu-ext.eicu_ext_data.") and t.endswith("_demo"), (name, t)
    n_creates += len(creates)
    # 2. no full-source or unsuffixed target reference remains
    assert SRC_OLD not in out, name
    for m in TGT.finditer(out):
        assert m.group(1).endswith("_demo"), (name, m.group(0))
    # 3. round trip
    back = out
    for old, new, n in adapters:
        back = back.replace(new, old)
    back = re.sub(r"(eicu-ext\.eicu_ext_data\.[A-Za-z0-9_]+)_demo\b", r"\1", back).replace(SRC_NEW, SRC_OLD)
    back = re.sub(r"'(v2_[a-z0-9_]*_eicu)_demo'", r"'\1'", back)
    assert back == text, f"{name}: generated file differs from source beyond the mapped names"

    eol = "\r\n" if b"\r\n" in raw else "\n"
    banner = BANNER.format(name=name)
    if adapters:
        banner += "-- Demo type adapters (same result under either column type):\n"
        banner += "".join(f"--   {o}\n--     -> {nw}\n" for o, nw, _ in adapters)
    body = banner.replace("\n", eol) + out
    dest = os.path.join(HERE, name.replace(".sql", "_demo.sql"))
    open(dest, "wb").write(body.encode("utf-8"))
    n_files += 1
    tabs = sorted(set(TGT.findall(out)))
    print(f"{os.path.basename(dest)}: {len(creates)} create(s); target tables: {', '.join(tabs)}")
print(f"{n_files} files, {n_creates} CREATE statements, all to *_demo tables")
