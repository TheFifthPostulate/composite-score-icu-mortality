# paper/make_withinclass_table.R -----------------------------------------------
# Write tables/within_class_correlation.tex: the pooled within-outcome
# correlation of the paired weights of evidence for every pair of channels,
# MIMIC-IV out of fold below the diagonal and eICU under the frozen bundle above
# it, channels in the patient-card order (paper/domain_order.R). Reads only the
# aggregate pair table of the channel-semantics run of record.
#   Rscript paper/make_withinclass_table.R [out/runs/chansem_<id>]
# ------------------------------------------------------------------------------
args <- commandArgs(trailingOnly = TRUE)
RUN <- if (length(args)) args[1] else "out/runs/chansem_20260914T084935"
source("paper/domain_order.R")
pr <- read.csv(file.path(RUN, "diagnostics", "within_class_correlation_pairs.csv"), stringsAsFactors = FALSE)
sig <- DOM$signal
stopifnot(nrow(pr) == choose(length(sig), 2), all(c(pr$a, pr$b) %in% sig))
M <- matrix(NA_real_, length(sig), length(sig), dimnames = list(sig, sig))
for (k in seq_len(nrow(pr))) {
  i <- match(pr$a[k], sig); j <- match(pr$b[k], sig)
  lo <- max(i, j); hi <- min(i, j)          # lower triangle MIMIC, upper eICU
  M[lo, hi] <- pr$r_within_mimic[k]; M[hi, lo] <- pr$r_within_eicu[k]
}
stopifnot(sum(is.na(M)) == length(sig))      # only the diagonal is empty
fmt <- function(x) {
  if (is.na(x)) return("--")
  if (round(x, 2) == 0) x <- 0                 # no negative zero
  s <- sub("^(-?)0\\.", "\\1.", sprintf("%.2f", x))
  s <- sub("^-", "$-$", s)
  if (abs(x) >= 0.5) paste0("\\textbf{", s, "}") else s
}
n <- length(sig)
dom <- DOM$domain
lines <- c(
  "% Generated by paper/make_withinclass_table.R from",
  paste0("% ", RUN, "/diagnostics/within_class_correlation_pairs.csv; do not edit by hand."),
  "\\begin{table}[p]",
  "\\centering",
  "\\caption{Pooled within-outcome correlation of the paired weights of evidence between each pair of channels, among stays that measured",
  "both channels: MIMIC-IV training stays out of fold below the diagonal and eICU stays under the frozen bundle above it. The covariance is",
  "computed within the stays that died and within the stays that survived, pooled by group size and scaled to a correlation. The channels are",
  "in the order of the patient card, grouped by physiological system, and the column numbers follow the row numbers. Bold marks an absolute",
  "correlation of at least 0.5.}",
  "\\label{tab:withincor}",
  "\\scriptsize",
  "\\setlength{\\tabcolsep}{2.2pt}",
  "\\begin{adjustbox}{max width=\\textwidth}",
  paste0("\\begin{tabular}{@{}r l l ", paste(rep("r", n), collapse = ""), "@{}}"),
  "\\toprule",
  paste0("& System & Channel & ", paste(seq_len(n), collapse = " & "), " \\\\"),
  "\\midrule")
for (i in seq_len(n)) {
  if (i > 1 && dom[i] != dom[i - 1]) lines <- c(lines, "\\addlinespace[2pt]")
  first <- i == 1 || dom[i] != dom[i - 1]
  cells <- vapply(seq_len(n), function(j) fmt(M[i, j]), "")
  lines <- c(lines, paste0(i, " & ", if (first) DOM_LAB[[dom[i]]] else "", " & ", CH_LAB[[sig[i]]], " & ",
                           paste(cells, collapse = " & "), " \\\\"))
}
lines <- c(lines, "\\bottomrule", "\\end{tabular}", "\\end{adjustbox}", "\\end{table}")
writeLines(lines, "paper/tables/within_class_correlation.tex", useBytes = TRUE)
cat("wrote paper/tables/within_class_correlation.tex:", n, "channels,", nrow(pr), "pairs per site\n")
